async function seedFirestore() {
  const collectionRef = db.collection("products");
  const collectionReadings = db.collection("readings");
  const collectionRituals = db.collection("rituals");

  console.log(
    `Iniciando carga de ${PRODUCTS_SEED.length} productos a Firestore...`,
  );

  for (const product of PRODUCTS_SEED) {
    await collectionRef.doc(product.id).set(product, { merge: true });
    console.log(`[+] Guardado: ${product.id}`);
  }

  console.log("Poblado de productos completado exitosamente.");

  console.log(
    `Iniciando carga de ${READINGS_SEED.length} lecturas a Firestore...`,
  );

  for (const reading of READINGS_SEED) {
    await collectionReadings.doc(reading.id).set(reading, { merge: true });
    console.log(`[+] Guardado: ${reading.id}`);
  }

  console.log("Poblado de lecturas completado exitosamente.");

  console.log(
    `Iniciando carga de ${RITUALS_SEED.length} rituales a Firestore...`,
  );

  for (const ritual of RITUALS_SEED) {
    await collectionRituals.doc(ritual.id).set(ritual, { merge: true });
    console.log(`[+] Guardado: ${ritual.id}`);
  }

  console.log("Poblado de rituales completado exitosamente.");
}

seedFirestore().catch(console.error);
